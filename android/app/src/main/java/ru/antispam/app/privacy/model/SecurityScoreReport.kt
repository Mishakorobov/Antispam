package ru.antispam.app.privacy.model

/**
 * Categorization of security and privacy issues affecting the device score.
 */
enum class SecurityIssueType {
    REGISTRY_OUTDATED,
    MIC_GUARD_DISABLED,
    NOTIFICATION_SPY_DETECTED,
    CLIPBOARD_GUARD_DISABLED,
    MITM_ROOT_CA_DETECTED,
    CRITICAL_ACCESSIBILITY_DETECTED,
    SUPERAPP_VPN_EXPOSED,
    STEALTH_GEO_DETECTED
}

/**
 * Severity level of a detected privacy issue.
 */
enum class SecurityIssueSeverity {
    CRITICAL,
    HIGH,
    MEDIUM
}

/**
 * An individual actionable issue detected on the device.
 */
data class SecurityIssue(
    val id: String,
    val type: SecurityIssueType,
    val title: String,
    val description: String,
    val severity: SecurityIssueSeverity,
    val scoreDeduction: Int,
    val actionLabel: String
)

/**
 * Inputs required for the security scoring algorithm.
 */
data class PrivacyAuditInput(
    val isRegistryUpToDate: Boolean,
    val isMicGuardEnabled: Boolean,
    val hasNotificationSpies: Boolean,
    val isClipboardGuardEnabled: Boolean,
    val hasMitmRootCa: Boolean,
    val hasCriticalAccessibility: Boolean = false,
    val hasVpnInventoryExposed: Boolean = false,
    val hasStealthGeoTrackers: Boolean = false
)

/**
 * Comprehensive report generated by SecurityScoreEngine.
 */
data class SecurityScoreReport(
    val score: Int, // 0..100
    val maxScore: Int = 100,
    val statusTitle: String,
    val statusDescription: String,
    val issues: List<SecurityIssue>,
    val categoryBreakdown: Map<String, Int>
)
